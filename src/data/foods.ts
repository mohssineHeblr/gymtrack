const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

export const FOOD_DATABASE: Food[] = Object.entries(CATALOG).flatMap(([category, rows]) =>
  rows.map(([id, name, calories, protein, carbs, fat, serving, servingLabel]) => ({
    id: `food-${id || slug(name)}`,
    name,
    category: category as FoodCategory,
    per100: { calories, protein, carbs, fat },
    servingGrams: serving ?? null,
    servingLabel,
    source: "builtin" as const,
  })),
);
